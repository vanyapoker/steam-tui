const fn remap<const N: usize, const M: usize>(base: &[*const (); N], map: [i16; M]) -> VTable<M> {
    let mut slots = [ptr::null::<()>(); M];
    let mut i = 0;
    while i < M {
        slots[i] = if map[i] < 0 {
            UNAVAILABLE.0[i]
        } else {
            base[map[i] as usize]
        };
        i += 1;
    }
    VTable(slots)
}

